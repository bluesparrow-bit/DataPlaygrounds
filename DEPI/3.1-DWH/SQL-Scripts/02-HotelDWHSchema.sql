/* =============================================================================
    HOTEL BOOKINGS | Star schema  (Microsoft SQL Server 2016+)

    Grain  : one fact row per booked room (one source BOOKING_ROOMS row)
    Tables : dim_guest, dim_hotel, dim_room, dim_date, fact_booking

    dim_date plays three roles in the fact table: booking date, check-in date
    and check-out date. It is loaded from dim_date.csv (date_key = yyyymmdd).

    gross_amount = number_of_nights x nightly_rate
    net_amount   = gross_amount - discount_amount

    Running the script again drops and rebuilds all tables (data is lost).
   ============================================================================= */

SET NOCOUNT ON;
GO

IF DB_ID(N'HotelBookingsDWH') IS NULL
    CREATE DATABASE HotelBookingsDWH;
GO

USE HotelBookingsDWH;
GO

/* -----------------------------------------------------------------------------
    1. Drop existing tables (fact first)
   ----------------------------------------------------------------------------- */
DROP TABLE IF EXISTS dbo.fact_booking, dbo.dim_guest, dbo.dim_hotel,
                    dbo.dim_room, dbo.dim_date;
GO

/* -----------------------------------------------------------------------------
    2. Dimensions
      *_key : surrogate key generated by the warehouse
      *_id  : business key from the source database (used for lookups)
   ----------------------------------------------------------------------------- */
CREATE TABLE dbo.dim_guest (
    guest_key      INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_dim_guest PRIMARY KEY,
    guest_id       INT               NOT NULL CONSTRAINT UQ_dim_guest_guest_id UNIQUE,
    guest_name     NVARCHAR(100)     NOT NULL,
    country        NVARCHAR(60)      NOT NULL,
    loyalty_level  NVARCHAR(20)      NOT NULL
);

CREATE TABLE dbo.dim_hotel (
    hotel_key   INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_dim_hotel PRIMARY KEY,
    hotel_id    INT               NOT NULL CONSTRAINT UQ_dim_hotel_hotel_id UNIQUE,
    hotel_name  NVARCHAR(100)     NOT NULL,
    city        NVARCHAR(60)      NOT NULL,
    region      NVARCHAR(60)      NOT NULL
);

CREATE TABLE dbo.dim_room (
    room_key        INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_dim_room PRIMARY KEY,
    room_id         INT               NOT NULL CONSTRAINT UQ_dim_room_room_id UNIQUE,
    room_number     NVARCHAR(10)      NOT NULL,
    room_type_name  NVARCHAR(40)      NOT NULL,
    capacity        TINYINT           NOT NULL
);

CREATE TABLE dbo.dim_date (
    date_key        INT      NOT NULL CONSTRAINT PK_dim_date PRIMARY KEY,   -- yyyymmdd, e.g. 20250315
    full_date       DATE     NOT NULL CONSTRAINT UQ_dim_date_full_date UNIQUE,
    month_number    TINYINT  NOT NULL CONSTRAINT CK_dim_date_month   CHECK (month_number   BETWEEN 1 AND 12),
    quarter_number  TINYINT  NOT NULL CONSTRAINT CK_dim_date_quarter CHECK (quarter_number BETWEEN 1 AND 4),
    year_number     SMALLINT NOT NULL
);
GO

/* -----------------------------------------------------------------------------
    3. Fact
    booking_id and booking_room_id are degenerate dimensions (source ids).
   ----------------------------------------------------------------------------- */
CREATE TABLE dbo.fact_booking (
    booking_room_key    INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_fact_booking PRIMARY KEY,
    booking_id          INT               NOT NULL,
    booking_room_id     INT               NOT NULL CONSTRAINT UQ_fact_booking_booking_room_id UNIQUE,

    guest_key           INT               NOT NULL CONSTRAINT FK_fact_booking_guest    REFERENCES dbo.dim_guest (guest_key),
    hotel_key           INT               NOT NULL CONSTRAINT FK_fact_booking_hotel    REFERENCES dbo.dim_hotel (hotel_key),
    room_key            INT               NOT NULL CONSTRAINT FK_fact_booking_room     REFERENCES dbo.dim_room  (room_key),

    booking_date_key    INT               NOT NULL CONSTRAINT FK_fact_booking_booking_date   REFERENCES dbo.dim_date (date_key),
    check_in_date_key   INT               NOT NULL CONSTRAINT FK_fact_booking_check_in_date  REFERENCES dbo.dim_date (date_key),
    check_out_date_key  INT               NOT NULL CONSTRAINT FK_fact_booking_check_out_date REFERENCES dbo.dim_date (date_key),

    number_of_nights    SMALLINT          NOT NULL,
    nightly_rate        DECIMAL(10,2)     NOT NULL,
    gross_amount        DECIMAL(12,2)     NOT NULL,
    discount_amount     DECIMAL(10,2)     NOT NULL,
    net_amount          DECIMAL(12,2)     NOT NULL
);

CREATE INDEX IX_fact_booking_guest_key          ON dbo.fact_booking (guest_key);
CREATE INDEX IX_fact_booking_hotel_key          ON dbo.fact_booking (hotel_key);
CREATE INDEX IX_fact_booking_room_key           ON dbo.fact_booking (room_key);
CREATE INDEX IX_fact_booking_booking_date_key   ON dbo.fact_booking (booking_date_key);
CREATE INDEX IX_fact_booking_check_in_date_key  ON dbo.fact_booking (check_in_date_key);
CREATE INDEX IX_fact_booking_check_out_date_key ON dbo.fact_booking (check_out_date_key);
CREATE INDEX IX_fact_booking_booking_id         ON dbo.fact_booking (booking_id);
GO
